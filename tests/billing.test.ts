import { createHmac } from 'node:crypto';
import { verifyStripeSignature, isEntitled, subscriptionToFields, encodeStripeParams } from '../src/lib/stripe';
const assert = (c: boolean, m: string) => { if (!c) { console.error('FAIL', m); process.exit(1); } };
const secret = 'whsec_test', body = '{"a":1}', t = 1000000;
const sig = createHmac('sha256', secret).update(`${t}.${body}`).digest('hex');
assert(verifyStripeSignature(body, `t=${t},v1=${sig}`, secret, t + 10), 'valid');
assert(!verifyStripeSignature(body + ' ', `t=${t},v1=${sig}`, secret, t + 10), 'tampered');
assert(!verifyStripeSignature(body, `t=${t},v1=${sig}`, 'other', t + 10), 'wrong secret');
assert(!verifyStripeSignature(body, `t=${t},v1=${sig}`, secret, t + 400), 'replay');
assert(!verifyStripeSignature(body, null, secret, t), 'no header');
assert(!verifyStripeSignature(body, `t=${t},v1=abcd`, secret, t), 'short sig');
assert(isEntitled({ status: 'active', comped: false }) && isEntitled({ status: 'trialing', comped: false }) && isEntitled({ status: 'none', comped: true }), 'ent+');
assert(!isEntitled({ status: 'past_due', comped: false }) && !isEntitled({ status: 'canceled', comped: false }) && !isEntitled(null), 'ent-');
const f = subscriptionToFields({ id: 'sub_1', customer: 'cus_1', status: 'active', current_period_end: 2000000000, cancel_at_period_end: true });
assert(f.stripe_customer_id === 'cus_1' && f.cancel_at_period_end && f.current_period_end!.startsWith('2033'), 'map');
const f2 = subscriptionToFields({ id: 's', customer: { id: 'c' }, status: 'active', items: { data: [{ current_period_end: 2000000000 }] } });
assert(f2.stripe_customer_id === 'c' && !!f2.current_period_end, 'map2');
const enc = encodeStripeParams({ mode: 'subscription', line_items: [{ quantity: 1, price_data: { currency: 'eur' } }], x: undefined }).join('&');
assert(enc === 'mode=subscription&line_items%5B0%5D%5Bquantity%5D=1&line_items%5B0%5D%5Bprice_data%5D%5Bcurrency%5D=eur', 'enc ' + enc);
console.log('billing tests OK');
